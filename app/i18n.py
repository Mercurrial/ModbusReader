SUPPORTED_LANGUAGES = ['ru', 'en']

def get_translator(lang: str = 'ru'):
    """Returns a translation function for the specified language."""
    if lang not in SUPPORTED_LANGUAGES:
        lang = 'en'
    
    def t(key: str) -> str:
        # Fallback to English, then to the key itself
        return STRINGS[lang].get(key, STRINGS['en'].get(key, key))
    
    return t
