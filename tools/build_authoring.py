def example_profile():
    return {"format": "modbusreader.profile", "version": 2, "name": "Example only",
            "registers": [{"addr": 0, "name": "Temperature", "type": "SHORT", "rw": "R", "scale": 0.1, "unit": "°C"},
                          {"addr": 1, "name": "Setpoint", "type": "SHORT", "rw": "RW", "scale": 0.1, "unit": "°C"}]}


def example_macro():
    return ('# Example addresses belong to example-map.json, not to a real device.\n'
            'for i in range(10):\n'
            '    record(sample=i, time=timestamp(), temperature=read("Temperature") * 0.1)\n'
            '    wait(1)\n')


def stubs():
    lines = ['"""Editor-only declarations: do not import this file in a macro."""',
             "class Register:", "    addr: int", "    type: str", "    name: str",
             "    def read(self) -> object: ...", "    def write(self, value) -> object: ...",
             "    @property", "    def value(self) -> object: ...", ""]
    for f in macro_api.FUNCTIONS:
        lines += [f"def {f.signature} -> {f.returns}:", f'    """{f.en}"""', "    ...", ""]
    return "\n".join(lines)


def generated_files():
    dump = lambda obj: json.dumps(obj, ensure_ascii=False, indent=2, allow_nan=False) + "\n"
    files = {Path(f"schemas/{k}.schema.json"): dump(v) for k, v in authoring.schemas().items()}
    files[Path("docs/reference/authoring.md")] = reference()
    files[Path("schemas/macro-api.pyi")] = stubs()
    files[SKILL / "references/authoring.md"] = reference()
    files[SKILL / "references/contract.json"] = dump(authoring.catalog())
    files[SKILL / "assets/example-map.json"] = dump(example_profile())
    files[SKILL / "assets/example-macro.py"] = example_macro()
    files[SKILL / "scripts/validate.py"] = ('"""Offline validator bundled from ModbusReader; Python stdlib only."""\n'
                                            'from core.authoring_cli import main\n\n'
                                            'if __name__ == "__main__":\n    raise SystemExit(main())\n')
    for name in MODULES:
        files[SKILL / f"scripts/core/{name}.py"] = (ROOT / f"core/{name}.py").read_text(encoding="utf-8")
    files[SKILL / "LICENSE"] = (ROOT / "LICENSE").read_text(encoding="utf-8")
    return files


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--zip", type=Path, help="Write an uploadable skill ZIP to this path")
    args = parser.parse_args(argv)
    files = generated_files()
    stale = []
    for path, content in files.items():
        target = ROOT / path
        expected = content.encode("utf-8")
        if args.check:
            if not target.exists() or target.read_text(encoding="utf-8") != content:
                stale.append(str(path))
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(expected)
    if stale:
        print("Generated files out of date:\n" + "\n".join(stale), file=sys.stderr)
        return 1
    if args.zip:
        args.zip.parent.mkdir(parents=True, exist_ok=True)
        # Explicit allowlist: no __pycache__, settings, device maps or local data.
        members = sorted([SKILL / "SKILL.md", *(p for p in files if p.is_relative_to(SKILL))])
        with zipfile.ZipFile(args.zip, "w", compression=zipfile.ZIP_DEFLATED) as archive:
            for path in members:
                info = zipfile.ZipInfo(str(path.relative_to(SKILL.parent)).replace("\\", "/"), (2026, 1, 1, 0, 0, 0))
                info.compress_type = zipfile.ZIP_DEFLATED
                info.external_attr = 0o100644 << 16
                archive.writestr(info, (ROOT / path).read_text(encoding="utf-8").encode("utf-8"))
        print(args.zip)
    print("Authoring artifacts are up to date." if args.check else "Generated authoring artifacts.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
