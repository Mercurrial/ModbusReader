"""Generate the offline contract and portable Claude/ChatGPT skill.

python tools/build_authoring.py [--check] [--zip PATH]
No dependencies, network, GUI or device access.
"""
import argparse
import json
from pathlib import Path
import sys
import zipfile

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from core import authoring, macro_api

SKILL = Path("skills/modbusreader-authoring")
MODULES = ("__init__", "authoring", "authoring_cli", "macro_api", "formats",
           "datatypes", "byteorder", "dash_model", "transports")


